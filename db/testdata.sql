-- ============================================================================
-- 12. 게시물 참여자 승인/반려
-- 일반 게시물은 비작성자 중 한 명만 REJECT, 나머지는 APPROVE로 평가한다.
-- REJECTED 게시물은 비작성자 전원이 REJECT로 평가한다.
-- ============================================================================
INSERT INTO post_approvals (
    user_id,
    post_id,
    approval_status,
    reject_reason,
    created_at,
    updated_at
)
SELECT evaluator.user_id,
       post.post_id,
       CASE
           WHEN post.post_status = 'REJECTED' THEN 'REJECT'
           WHEN evaluator.user_id = (
               SELECT MIN(candidate.user_id)
               FROM round_history candidate
               WHERE candidate.round_id = post.round_id
                 AND candidate.user_id <> post.user_id
           ) THEN 'REJECT'
           ELSE 'APPROVE'
       END,
       CASE
           WHEN post.post_status = 'REJECTED'
               THEN '인증 내용이 챌린지 기준을 충족하지 않습니다.'
           WHEN evaluator.user_id = (
               SELECT MIN(candidate.user_id)
               FROM round_history candidate
               WHERE candidate.round_id = post.round_id
                 AND candidate.user_id <> post.user_id
           ) THEN '인증 내용 확인을 위해 보완이 필요합니다.'
           ELSE NULL
       END,
       post.status_changed_at,
       post.status_changed_at
FROM posts post
INNER JOIN round_history evaluator
        ON evaluator.round_id = post.round_id
       AND evaluator.user_id <> post.user_id
ORDER BY post.post_id, evaluator.user_id;

-- ============================================================================
-- 13. 게시물 참여자 반응
-- 작성자를 제외한 라운드 참여자 전원이 반응하며, 가장 작은 user_id 한 명은 DISLIKE한다.
-- ============================================================================
INSERT INTO post_reactions (
    post_id,
    user_id,
    reaction_type,
    created_at,
    updated_at
)
SELECT post.post_id,
       evaluator.user_id,
       CASE
           WHEN evaluator.user_id = (
               SELECT MIN(candidate.user_id)
               FROM round_history candidate
               WHERE candidate.round_id = post.round_id
                 AND candidate.user_id <> post.user_id
           ) THEN 'DISLIKE'
           ELSE 'LIKE'
       END,
       DATE_ADD(post.posted_at, INTERVAL 30 MINUTE),
       DATE_ADD(post.posted_at, INTERVAL 30 MINUTE)
FROM posts post
INNER JOIN round_history evaluator
        ON evaluator.round_id = post.round_id
       AND evaluator.user_id <> post.user_id
ORDER BY post.post_id, evaluator.user_id;

-- ============================================================================
-- 14. 게시물 댓글
-- 작성자를 제외한 라운드 참여자 중 user_id 순서가 빠른 두 명이 댓글을 작성한다.
-- ============================================================================
INSERT INTO post_comments (
    user_id,
    post_id,
    content,
    created_at,
    updated_at
)
SELECT ranked.user_id,
       ranked.post_id,
       CASE ranked.evaluator_no
           WHEN 1 THEN '오늘도 목표 달성 수고했어요!'
           ELSE '꾸준한 인증 응원합니다!'
       END,
       DATE_ADD(ranked.posted_at, INTERVAL 60 MINUTE),
       DATE_ADD(ranked.posted_at, INTERVAL 60 MINUTE)
FROM (
    SELECT post.post_id,
           post.posted_at,
           evaluator.user_id,
           ROW_NUMBER() OVER (
               PARTITION BY post.post_id
               ORDER BY evaluator.user_id
           ) AS evaluator_no
    FROM posts post
    INNER JOIN round_history evaluator
            ON evaluator.round_id = post.round_id
           AND evaluator.user_id <> post.user_id
) ranked
WHERE ranked.evaluator_no <= 2
ORDER BY ranked.post_id, ranked.evaluator_no;

-- 게시물의 비정규화된 반응·댓글 개수를 실제 생성 데이터와 맞춘다.
UPDATE posts post
SET post.like_count = (
        SELECT COUNT(*)
        FROM post_reactions reaction
        WHERE reaction.post_id = post.post_id
          AND reaction.reaction_type = 'LIKE'
    ),
    post.dislike_count = (
        SELECT COUNT(*)
        FROM post_reactions reaction
        WHERE reaction.post_id = post.post_id
          AND reaction.reaction_type = 'DISLIKE'
    ),
    post.comment_count = (
        SELECT COUNT(*)
        FROM post_comments comment
        WHERE comment.post_id = post.post_id
    )
WHERE post.round_id IN (5, 6, 9, 10, 12, 13, 17, 18);
